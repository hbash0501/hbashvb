        string.Join(" ", BasiraEngine.Normalize(name ?? "").Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(w => w.Length > 3 && w.StartsWith("ال", StringComparison.Ordinal) ? w[2..] : w));

    public CategoryDef? Find(string name) => Categories.FirstOrDefault(c => NameKey(c.Name) == NameKey(name));

