    public static Taxonomy FromJson(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return Default();
        var t = JsonSerializer.Deserialize<Taxonomy>(json, Json) ?? Default();
        t.Categories = t.Categories.Where(c => !string.IsNullOrWhiteSpace(c.Name)).ToList();
        return t.Categories.Count == 0 ? Default() : t;
    }

